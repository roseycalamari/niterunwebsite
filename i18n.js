  function getLang() {
    try {
      return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
    } catch (e) {
      return DEFAULT_LANG;
    }
  }

  function setLang(lang) {
    if (!DICT[lang]) lang = DEFAULT_LANG;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    applyLang(lang);
  }

  function t(key, vars) {
    var lang = getLang();
    var table = DICT[lang] || DICT[DEFAULT_LANG];
    var str = (table && table[key]) || (DICT[DEFAULT_LANG] && DICT[DEFAULT_LANG][key]) || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = str.replace(new RegExp('\\{\\{\\s*' + k + '\\s*\\}\\}', 'g'), String(vars[k]));
      });
    }
    return str;
  }

  function applyLang(lang) {
    try {
      document.documentElement.setAttribute('lang', lang === 'pt-PT' ? 'pt-PT' : 'en');
    } catch (e) {}

    // Text nodes (optionally with vars via data-i18n-vars='{"x":1}')
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!key) return;
      var vars = null;
      var rawVars = el.getAttribute('data-i18n-vars');
      if (rawVars) {
        try { vars = JSON.parse(rawVars); } catch (e) { vars = null; }
      }
      el.textContent = t(key, vars || undefined);
    });

    // Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (!key) return;
      el.setAttribute('placeholder', t(key));
    });

    // Titles
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      if (!key) return;
      el.setAttribute('title', t(key));
    });

    // aria-label
    document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria-label');
      if (!key) return;
      el.setAttribute('aria-label', t(key));
    });

    // Let pages react
    try {
      document.dispatchEvent(new CustomEvent('niterun:lang', { detail: { lang: lang } }));
    } catch (e) {}

    syncLangControls(lang);
  }

  function syncLangControls(lang) {
    document.querySelectorAll('select[data-lang-switcher]').forEach(function (sel) {
      sel.value = lang;
    });
    document.querySelectorAll('[data-lang-switcher-group]').forEach(function (group) {
      group.querySelectorAll('[data-lang]').forEach(function (btn) {
        var code = btn.getAttribute('data-lang');
        var on = code === lang;
        btn.classList.toggle('lang-switch__btn--active', on);
        btn.setAttribute('aria-pressed', on ? 'true' : 'false');
      });
    });
  }

  function initSwitchers() {
    document.querySelectorAll('select[data-lang-switcher]').forEach(function (sel) {
      sel.addEventListener('change', function () {
        setLang(sel.value);
      });
    });
    document.querySelectorAll('[data-lang-switcher-group]').forEach(function (group) {
      group.querySelectorAll('[data-lang]').forEach(function (btn) {
        btn.addEventListener('click', function () {
          var code = btn.getAttribute('data-lang');
          if (code) setLang(code);
        });
      });
    });
  }

  window.NiteRunI18n = { t: t, getLang: getLang, setLang: setLang, apply: function () { applyLang(getLang()); } };

  document.addEventListener('DOMContentLoaded', function () {
    initSwitchers();
    applyLang(getLang());
  });
